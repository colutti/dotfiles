def build_hdr_calibration_target(
    current: dict[str, Any],
    *,
    sdrbrightness: float,
    sdrsaturation: float,
    sdr_eotf: str,
    sdr_min_luminance: float,
    sdr_max_luminance: float,
) -> dict[str, Any]:
    """Build a safe live HDR preview without changing the display layout."""
    target = dict(current)
    target.update({"bitdepth": 10, "color_mode": "hdredid", "vrr": False})
    target["hdr_tuning"] = {
        "supports_wide_color": True,
        "supports_hdr": True,
        "sdrbrightness": sdrbrightness,
        "sdrsaturation": sdrsaturation,
        "sdr_eotf": sdr_eotf,
        "sdr_min_luminance": sdr_min_luminance,
        "sdr_max_luminance": int(round(sdr_max_luminance)),
        "min_luminance": 0.25,
        "max_luminance": 480,
        "max_avg_luminance": 302,
    }
    return target


