def validate_settings(settings: dict[str, Any]) -> None:
    allowed = {"schema_version", "theme", "theme_override", "monitors", "profile"}
    if not isinstance(settings, dict):
        raise ValueError("settings must be an object")
    missing = allowed - set(settings)
    if missing:
        raise ValueError(f"missing setting: {sorted(missing)[0]}")
    unknown = set(settings) - allowed
    if unknown:
        raise ValueError(f"unknown setting: {sorted(unknown)[0]}")
    if settings.get("schema_version") != 1:
        raise ValueError("unsupported settings schema")
    theme_slugs = {
        path.parent.name for path in (ROOT / "themes").glob("*/manifest.json")
    }
    if settings["theme"] not in theme_slugs:
        raise ValueError(f"invalid theme: {settings['theme']}")
    if not isinstance(settings["theme_override"], bool):
        raise ValueError("theme_override must be boolean")
    if not isinstance(settings["monitors"], dict) or not settings["monitors"]:
        raise ValueError("monitors must be a non-empty object")
    for output, monitor in settings["monitors"].items():
        fields = {
            "mode",
            "position",
            "scale",
            "bitdepth",
            "color_mode",
            "hdr_fullscreen_passthrough",
        }
        if not isinstance(monitor, dict):
            raise ValueError(f"monitor {output} must be an object")
        missing_monitor = fields - set(monitor)
        if missing_monitor:
            raise ValueError(
                f"missing monitor setting for {output}: {sorted(missing_monitor)[0]}"
            )
        optional_fields = {"hdr_tuning"}
        unknown_monitor = set(monitor) - fields - optional_fields
        if unknown_monitor:
            raise ValueError(
                f"unknown monitor setting for {output}: {sorted(unknown_monitor)[0]}"
            )
        if not re.fullmatch(r"\d+x\d+@\d+(?:\.\d+)?", str(monitor["mode"])):
            raise ValueError(f"invalid mode for {output}")
        if not re.fullmatch(r"-?\d+x-?\d+", str(monitor["position"])):
            raise ValueError(f"invalid position for {output}")
        if not 0.5 <= float(monitor["scale"]) <= 4:
            raise ValueError(f"invalid scale for {output}")
        if monitor["bitdepth"] not in {8, 10}:
            raise ValueError(f"invalid bitdepth for {output}")
        if monitor["color_mode"] not in {
            "srgb",
            "wide",
            "hdr",
            "hdredid",
            "dciedid",
            "dp3",
        }:
            raise ValueError(f"invalid color mode for {output}")
        if not isinstance(monitor["hdr_fullscreen_passthrough"], bool):
            raise ValueError(f"HDR flag must be boolean for {output}")
        tuning = monitor.get("hdr_tuning")
        if tuning is not None:
            allowed_tuning = {
                "sdrbrightness", "sdrsaturation", "sdr_eotf",
                "sdr_min_luminance", "sdr_max_luminance", "min_luminance",
                "max_luminance", "max_avg_luminance", "supports_wide_color",
                "supports_hdr",
            }
            if not isinstance(tuning, dict) or set(tuning) - allowed_tuning:
                raise ValueError(f"invalid HDR tuning for {output}")
            for key, value in tuning.items():
                if key == "sdr_eotf":
                    if value not in {"default", "srgb", "gamma22"}:
                        raise ValueError(f"invalid HDR EOTF for {output}")
                elif key in {"supports_wide_color", "supports_hdr"}:
                    if not isinstance(value, bool):
                        raise ValueError(f"invalid HDR capability for {output}: {key}")
                elif not isinstance(value, (int, float)) or isinstance(value, bool):
                    raise ValueError(f"invalid HDR tuning value for {output}: {key}")
    if not isinstance(settings["profile"], dict):
        raise ValueError("profile must be an object")
    profile_fields = {"game", "power", "dnd"}
    if set(settings["profile"]) != profile_fields:
        raise ValueError("profile must contain game, power and dnd")
    if settings["profile"]["game"] not in {"on", "off"}:
        raise ValueError("invalid game profile")
    if settings["profile"]["power"] not in {
        "balanced",
        "performance",
        "power-saver",
    }:
        raise ValueError("invalid power profile")
    if not isinstance(settings["profile"]["dnd"], bool):
        raise ValueError("DND must be boolean")


def read_settings() -> dict[str, Any]:
    path = settings_path()
    settings = json.loads(path.read_text()) if path.exists() else default_settings()
    validate_settings(settings)
    return settings


def replace_settings(source: Path) -> dict[str, Any]:
    settings = json.loads(source.read_text())
    validate_settings(settings)
    destination = settings_path()
    if destination.exists():
        current = json.loads(destination.read_text())
        previous = STATE / "previous-settings.json"
        if current != settings and not previous.exists():
            atomic_json(previous, current)
    atomic_json(destination, settings)
    return settings


def set_monitor_hdr(output: str, enabled: bool) -> dict[str, Any]:
    settings = read_settings()
    monitor = settings["monitors"].get(output)
    if monitor is None:
        raise ValueError(f"unknown monitor: {output}")
    if not monitor["hdr_fullscreen_passthrough"]:
        raise ValueError(f"monitor is not HDR-capable: {output}")
    monitor["bitdepth"] = 10 if enabled else 8
    monitor["color_mode"] = "hdr" if enabled else "srgb"
    if enabled and output == "DP-2":
        monitor["hdr_tuning"] = {
            "sdrbrightness": 1.2,
            "sdrsaturation": 0.98,
            "sdr_eotf": "srgb",
            "sdr_min_luminance": 0.25,
            "sdr_max_luminance": 480,
            "min_luminance": 0.25,
            "max_luminance": 480,
            "max_avg_luminance": 302,
        }
    elif not enabled:
        monitor.pop("hdr_tuning", None)
    validate_settings(settings)
    atomic_json(settings_path(), settings)
    return settings


def theme_manifests() -> list[dict[str, Any]]:
    manifests = []
    for path in sorted((ROOT / "themes").glob("*/manifest.json")):
        manifests.append(json.loads(path.read_text()))
    return manifests


class ThemeManager:
    def __init__(self, root: Path = ROOT, state: Path = STATE):
        self.root, self.state = root, state

    def manifest(self, slug: str) -> dict[str, Any]:
        path = self.root / "themes" / slug / "manifest.json"
        if not path.exists():
            raise ValueError(f"unknown theme: {slug}")
        manifest = json.loads(path.read_text())
        if manifest["schema_version"] != 1 or manifest["slug"] != slug:
            raise ValueError(f"invalid theme manifest: {slug}")
        return manifest

    def apply(
        self,
        slug: str,
        preview: bool = False,
        preview_timeout: int = 20,
    ) -> dict[str, Any]:
        manifest = self.manifest(slug)
        wallpaper = self.root / "themes" / slug / manifest["wallpaper"]["file"]
        checksum = hashlib.sha256(wallpaper.read_bytes()).hexdigest()
        if checksum != manifest["wallpaper"]["sha256"]:
            raise ValueError(f"wallpaper checksum mismatch: {slug}")
        generated = self.state / "generated"
        current = generated / "theme.json"
        previous = self.state / "previous-theme.json"
        old = json.loads(current.read_text()) if current.exists() else None
        self.state.mkdir(parents=True, exist_ok=True)
        stage = Path(tempfile.mkdtemp(prefix=".theme-generation-", dir=self.state))
        try:
            atomic_json(stage / "theme.json", manifest)
            self._write_generated(manifest, wallpaper, stage)
            self._publish_generation(stage)
        except BaseException:
            if stage.exists():
                shutil.rmtree(stage)
            raise
        if old and old.get("slug") != slug:
            atomic_json(previous, old)
        status = {
            "slug": slug,
            "preview": preview,
            "applied_at": int(time.time()),
        }
        if preview:
            status["token"] = hashlib.md5(
                os.urandom(32), usedforsecurity=False
            ).hexdigest()
            status["timeout"] = preview_timeout
        atomic_json(self.state / "theme-status.json", status)
        if self._is_live_state():
            if not preview:
                self._update_settings(slug)
            self._notify_reload(manifest)
            if preview:
                subprocess.Popen(
                    [
                        sys.executable,
                        str(Path(__file__).resolve()),
                        "_theme-timeout",
                        str(status["token"]),
                        str(preview_timeout),
                    ],
                    start_new_session=True,
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
        return manifest

    def expire_preview(self, token: str) -> bool:
        status_path = self.state / "theme-status.json"
        if not status_path.exists():
            return False
        status = json.loads(status_path.read_text())
        if not status.get("preview") or status.get("token") != token:
            return False
        self.rollback()
        return True

    def _publish_generation(self, stage: Path) -> None:
        generated = self.state / "generated"
        old = self.state / f".theme-previous-{os.getpid()}"
        if old.exists() or old.is_symlink():
            if old.is_dir() and not old.is_symlink():
                shutil.rmtree(old)
            else:
                old.unlink()
        had_current = generated.exists() or generated.is_symlink()
        if had_current:
            os.replace(generated, old)
        try:
            os.replace(stage, generated)
        except BaseException:
            if had_current:
                os.replace(old, generated)
            raise
        if had_current:
            if old.is_dir() and not old.is_symlink():
                shutil.rmtree(old)
            else:
                old.unlink(missing_ok=True)

    def _update_settings(self, slug: str) -> None:
        config = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
        path = config / "colutti-desktop/settings.json"
        settings = json.loads(path.read_text()) if path.exists() else default_settings()
        settings["theme"] = slug
        settings["theme_override"] = True
        validate_settings(settings)
        atomic_json(path, settings)

