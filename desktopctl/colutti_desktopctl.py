def doctor() -> tuple[dict[str, Any], int]:
    required = [
        "Hyprland",
        "qs",
        "uwsm",
        "hyprctl",
        "wpctl",
        "grim",
        "slurp",
        "fuzzel",
        "swaync-client",
        "hyprsunset",
    ]
    checks = [{"name": command, "status": command_status(command)} for command in required]
    checks.extend([
        service_check("uwsm-session", "wayland-wm@Hyprland.service"),
        service_check("shell", "colutti-quickshell.service"),
        service_check("wallpaper", "hyprpaper.service"),
        service_check("idle", "hypridle.service"),
        service_check("sunset", "hyprsunset.service"),
        service_check("clipboard", "colutti-clipboard.service"),
        service_check("notifications", "swaync.service"),
        service_check("polkit-agent", "plasma-polkit-agent.service"),
        service_check("portal-frontend", "xdg-desktop-portal.service"),
        service_check("portal-hyprland", "xdg-desktop-portal-hyprland.service"),
        service_check("portal-kde", "plasma-xdg-desktop-portal-kde.service"),
        bus_owner_check("notification-service", "org.freedesktop.Notifications"),
        storage_headroom_check(),
        gamemode_group_check(),
    ])
    try:
        settings = read_settings()
        checks.extend([
            monitor_layout_check(settings),
            primary_panel_check(),
            audio_defaults_check(),
            restored_apps_check(),
        ])
        generated_path = STATE / "generated/theme.json"
        generated = json.loads(generated_path.read_text())
        match = settings["theme"] == generated["slug"]
        checks.append({
            "name": "theme-state",
            "status": "ok" if match else "error",
            "detail": {
                "settings": settings["theme"],
                "generated": generated["slug"],
            },
        })
    except (KeyError, OSError, ValueError, json.JSONDecodeError) as error:
        checks.append({
            "name": "theme-state",
            "status": "error",
            "detail": str(error),
        })
    manifest = json.loads((ROOT / "packages.json").read_text())
    installed_packages: set[str] = set()
    if shutil.which("pacman"):
        installed = subprocess.run(
            ["pacman", "-Qq"],
            text=True,
            capture_output=True,
            check=False,
        )
        installed_packages = set(installed.stdout.splitlines())
    missing_packages = sorted(
        set(manifest["install"]) - installed_packages
    )
    checks.append({
        "name": "official-packages",
        "status": "ok" if not missing_packages else "error",
        "detail": missing_packages,
    })
    missing_flatpaks = []
    for application in manifest.get("flatpak_apps", []):
        result = subprocess.run(
            ["flatpak", "info", application],
            text=True,
            capture_output=True,
            check=False,
        ) if shutil.which("flatpak") else None
        if result is None or result.returncode != 0:
            missing_flatpaks.append(application)
    checks.append({
        "name": "flatpak-apps",
        "status": "ok" if not missing_flatpaks else "error",
        "detail": missing_flatpaks,
    })
    foreign = subprocess.run(
        ["pacman", "-Qm"], text=True, capture_output=True, check=False
    ) if shutil.which("pacman") else None
    checks.append({
        "name": "foreign-packages",
        "status": "ok" if foreign and not foreign.stdout.strip() else "warning",
        "detail": [] if foreign is None else foreign.stdout.splitlines(),
    })
    if shutil.which("systemctl"):
        failed = subprocess.run(
            ["systemctl", "--user", "--failed", "--no-legend", "--plain"],
            text=True,
            capture_output=True,
            check=False,
        )
        failed_units = [
            line.split()[0] for line in failed.stdout.splitlines() if line.split()
        ]
        checks.append({
            "name": "failed-user-units",
            "status": "ok" if not failed_units else "warning",
            "detail": failed_units,
        })
    report = {"schema_version": 1, "checks": checks}
    return report, 0 if all(c["status"] == "ok" for c in checks) else 2


def set_game_profile(action: str) -> dict[str, Any]:
    path = STATE / "game-profile.json"
    current = json.loads(path.read_text()) if path.exists() else {"state": "off"}
    if action == "status":
        return current
    if action == current.get("state"):
        return current
    previous_power = current.get("previous_power", "balanced")
    target_power = previous_power
    if shutil.which("powerprofilesctl"):
        if action == "on":
            result = subprocess.run(
                ["powerprofilesctl", "get"],
                text=True,
                capture_output=True,
                check=False,
            )
            if result.returncode == 0 and result.stdout.strip():
                previous_power = result.stdout.strip()
            target_power = "performance"
        subprocess.run(
            ["powerprofilesctl", "set", target_power],
            check=False,
        )
    previous_animations = bool(current.get("previous_animations", True))
    previous_blur = bool(current.get("previous_blur", True))
    if shutil.which("hyprctl") and os.environ.get("HYPRLAND_INSTANCE_SIGNATURE"):
        if action == "on":
            for option, field in (
                ("animations:enabled", "animations"),
                ("decoration:blur:enabled", "blur"),
            ):
                result = subprocess.run(
                    ["hyprctl", "getoption", option, "-j"],
                    text=True,
                    capture_output=True,
                    check=False,
                )
                if result.returncode == 0:
                    try:
                        value = bool(json.loads(result.stdout)["bool"])
                        if field == "animations":
                            previous_animations = value
                        else:
                            previous_blur = value
                    except (KeyError, json.JSONDecodeError):
                        pass
        animations = False if action == "on" else previous_animations
        blur = False if action == "on" else previous_blur
        expression = (
            "hl.config({ animations = { enabled = "
            + str(animations).lower()
            + " }, decoration = { blur = { enabled = "
            + str(blur).lower()
            + " } } })"
        )
        subprocess.run(["hyprctl", "eval", expression], check=False, capture_output=True)
    previous_dnd = current.get("previous_dnd", False)
    if shutil.which("swaync-client"):
        if action == "on":
            result = subprocess.run(
                ["swaync-client", "-D"], text=True, capture_output=True, check=False
            )
            previous_dnd = result.stdout.strip().lower() == "true"
        subprocess.run(
            ["swaync-client", "-dn" if action == "on" or previous_dnd else "-df"],
            check=False,
            capture_output=True,
        )
    if shutil.which("systemctl"):
        subprocess.run(
            [
                "systemctl",
                "--user",
                "start" if action == "on" else "stop",
                "colutti-game-inhibit.service",
            ],
            check=False,
            capture_output=True,
        )
    profile = {
        "state": action,
        "previous_power": previous_power,
        "previous_dnd": previous_dnd,
        "previous_animations": previous_animations,
        "previous_blur": previous_blur,
        "changed_at": int(time.time()),
    }
    atomic_json(path, profile)
    config = Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config"))
    settings_path = config / "colutti-desktop/settings.json"
    settings = (
        json.loads(settings_path.read_text())
        if settings_path.exists()
        else default_settings()
    )
    settings["profile"].update({
        "game": action,
        "power": target_power,
        "dnd": True if action == "on" else previous_dnd,
    })
    validate_settings(settings)
    atomic_json(settings_path, settings)
    return profile


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(prog="colutti-desktopctl")
    commands = root.add_subparsers(dest="command", required=True)
    theme = commands.add_parser("theme")
    themes = theme.add_subparsers(dest="action", required=True)
    for action in ("list", "rollback"):
        item = themes.add_parser(action)
        item.add_argument("--json", action="store_true")
    for action in ("preview", "apply"):
        item = themes.add_parser(action)
        item.add_argument("slug")
        item.add_argument("--json", action="store_true")
    monitors = commands.add_parser("monitors")
    monitor_actions = monitors.add_subparsers(dest="action", required=True)
    apply_cmd = monitor_actions.add_parser("apply")
    apply_cmd.add_argument("--timeout", type=int, default=20)
    confirm = monitor_actions.add_parser("confirm")
    confirm.add_argument("token")
    monitor_actions.add_parser("rollback")
    hdr = monitor_actions.add_parser("hdr")
    hdr.add_argument("state", choices=["on", "off", "status"])
    profile = commands.add_parser("profile")
    profile.add_argument("kind", choices=["game"])
    profile.add_argument("action", choices=["on", "off", "status"])
    commands.add_parser("validate")
    check = commands.add_parser("doctor")
    check.add_argument("--json", action="store_true")
    session = commands.add_parser("session")
    session.add_argument("action", choices=["restore", "status"])
    settings = commands.add_parser("settings")
    settings_actions = settings.add_subparsers(dest="action", required=True)
    settings_actions.add_parser("show")
    settings_apply = settings_actions.add_parser("apply")
    settings_apply.add_argument("path", type=Path)
    settings_hdr = settings_actions.add_parser("set-hdr")
    settings_hdr.add_argument("output")
    settings_hdr.add_argument("state", choices=["on", "off"])
    timeout = commands.add_parser("_monitor-timeout")
    timeout.add_argument("token")
    timeout.add_argument("seconds", type=int)
    theme_timeout = commands.add_parser("_theme-timeout")
    theme_timeout.add_argument("token")
    theme_timeout.add_argument("seconds", type=int)
    return root


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    try:
        if args.command == "theme":
            if args.action == "list":
                result = theme_manifests()
            elif args.action == "rollback":
                result = ThemeManager().rollback()
            else:
                result = ThemeManager().apply(args.slug, preview=args.action == "preview")
            print(json.dumps(result, indent=2) if args.json else (
                "\n".join(item["slug"] for item in result) if isinstance(result, list)
                else result["slug"]
            ))
        elif args.command == "monitors":
            manager = MonitorManager()
            if args.action == "apply":
                print(manager.apply(args.timeout))
            elif args.action == "confirm":
                manager.confirm(args.token)
            elif args.action == "hdr":
                print(json.dumps(manager.hdr(args.state), indent=2))
            else:
                manager.rollback()
        elif args.command == "_monitor-timeout":
            time.sleep(args.seconds)
            pending = STATE / "pending-monitor.json"
            if pending.exists() and json.loads(pending.read_text())["token"] == args.token:
                MonitorManager().rollback()
        elif args.command == "_theme-timeout":
            time.sleep(args.seconds)
            ThemeManager().expire_preview(args.token)
        elif args.command == "doctor":
            report, code = doctor()
            print(json.dumps(report, indent=2))
            return code
        elif args.command == "validate":
            return subprocess.run([str(ROOT / "install.sh"), "validate"]).returncode
        elif args.command == "profile":
            print(set_game_profile(args.action)["state"])
        elif args.command == "session":
            script = ROOT / "scripts/session-restore"
            if args.action == "restore":
                return subprocess.run([str(script)]).returncode
            print("ready" if os.environ.get("HYPRLAND_INSTANCE_SIGNATURE") else "offline")
        elif args.command == "settings":
            if args.action == "show":
                result = read_settings()
            elif args.action == "apply":
                result = replace_settings(args.path)
            else:
                result = set_monitor_hdr(args.output, args.state == "on")
            print(json.dumps(result, indent=2))
        return 0
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
